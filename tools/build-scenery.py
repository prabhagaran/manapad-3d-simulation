"""Regenerate the 3D scenery data from assets/manapad-satellite.jpg.

Run from anywhere:  python3 tools/build-scenery.py
Needs: numpy, opencv-python.

Writes
  assets/water-mask.png        soft water mask (white = water) for the animated sea surface
  scripts/scenery-data.js      trees + building blocks (world metres), read by world.js
  scripts/texture-data.js      the satellite image and water mask as data URIs, so the
                               page also works when opened straight from disk (file://),
                               where browsers refuse to give WebGL images loaded from files.

Coordinates: original-screenshot pixels (1 px ~ 1 m at the screenshot's scale bar).
World X = x - 1100, world Z = y - 650. The satellite image covers x 215-1636, y 62-882
at 1.25 image px per unit. Buildings and trees are DERIVED FROM IMAGE COLOUR, not surveyed:
building footprints are grid cells that look like roofs, heights are random.
"""
import base64, json, os, random
import cv2
import numpy as np

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
random.seed(7); np.random.seed(7)
img = cv2.imread(os.path.join(ROOT, "assets", "manapad-satellite.jpg"))
h, w = img.shape[:2]
hsv = cv2.cvtColor(img, cv2.COLOR_BGR2HSV).astype(np.float32)
H = hsv[..., 0] * 2; S = hsv[..., 1] / 255; V = hsv[..., 2] / 255
b, g, r = [img[..., i].astype(np.float32) for i in range(3)]

water = (((H >= 150) & (H <= 215) & (S > 0.25)) | ((b > r + 25) & (g > r + 10) & (S > 0.3))).astype(np.uint8) * 255
water = cv2.morphologyEx(water, cv2.MORPH_OPEN, np.ones((5, 5), np.uint8))
water = cv2.morphologyEx(water, cv2.MORPH_CLOSE, np.ones((9, 9), np.uint8))
n, lab, st, _ = cv2.connectedComponentsWithStats(water)
for i in range(1, n):
    if st[i, 4] < 2500:          # blue tarps on roofs are not water
        water[lab == i] = 0
soft = cv2.GaussianBlur(water, (0, 0), 2.5)
cv2.imwrite(os.path.join(ROOT, "assets", "water-mask.png"), cv2.resize(soft, (888, 512), interpolation=cv2.INTER_AREA))

veg = ((H >= 70) & (H < 150) & (S > 0.25) & (V < 0.75) & (g > r)).astype(np.uint8)
veg[water > 0] = 0
# settlement (town side of the channel), hand-drawn in image px
settle = np.array([(0, 370), (104, 296), (296, 237), (429, 222), (488, 266), (592, 414), (696, 533), (829, 666),
                   (947, 740), (1066, 829), (1184, 903), (1302, 977), (1406, 1025), (0, 1025)], np.int32)
smask = np.zeros((h, w), np.uint8); cv2.fillPoly(smask, [settle], 1)
dist = cv2.distanceTransform((water == 0).astype(np.uint8), cv2.DIST_L2, 5)
smask[dist < 30] = 0             # keep the beach strip (existing boats) free
tmask = smask.copy(); tmask[0:370, 0:700] = 1


def world(ix, iy):
    return (ix / 1.25 + 215 - 1100, iy / 1.25 + 62 - 650)


trees = []
vegd = cv2.erode(veg, np.ones((3, 3), np.uint8))
step = 8
for y in range(0, h, step):
    for x in range(0, w, step):
        jx = min(w - 1, x + random.randint(0, step - 1)); jy = min(h - 1, y + random.randint(0, step - 1))
        if vegd[jy, jx] and tmask[jy, jx] and water[jy, jx] == 0:
            X, Z = world(jx, jy)
            trees.append([round(X, 1), round(Z, 1), round(random.uniform(5, 11), 1), random.randint(0, 2)])

road = ((S < 0.2) & (V > 0.45) & (V < 0.78)) | ((H >= 20) & (H <= 50) & (S > 0.15) & (S < 0.45) & (V > 0.55))
bld = []
cs = 8
for y in range(0, h - cs, cs):
    for x in range(0, w - cs, cs):
        if not smask[y + cs // 2, x + cs // 2]:
            continue
        cell = (slice(y, y + cs), slice(x, x + cs))
        if water[cell].mean() > 40 or veg[cell].mean() > 0.35 or road[cell].mean() > 0.55:
            continue
        X, Z = world(x + cs / 2, y + cs / 2)
        s = cs / 1.25
        bld.append([round(X, 1), round(Z, 1), round(s * random.uniform(.78, .95), 1), round(s * random.uniform(.78, .95), 1),
                    round(random.choice([3.2, 3.6, 4, 4.5, 6.5, 7, 9.5]), 1)])

with open(os.path.join(ROOT, "scripts", "scenery-data.js"), "w") as f:
    f.write("/* Generated by tools/build-scenery.py from the satellite image. Not surveyed.\n"
            "   trees: [x, z, height m, kind]; buildings: [x, z, w, d, height m] in world metres. */\n")
    f.write("window.SCENERY=" + json.dumps({"trees": trees, "buildings": bld}, separators=(",", ":")) + ";\n")


def uri(path, mime):
    with open(path, "rb") as fh:
        return "data:%s;base64,%s" % (mime, base64.b64encode(fh.read()).decode())


with open(os.path.join(ROOT, "scripts", "texture-data.js"), "w") as f:
    f.write("/* Generated by tools/build-scenery.py: assets embedded so file:// works. */\n")
    f.write("window.TEX={sat:%s,water:%s};\n" % (
        json.dumps(uri(os.path.join(ROOT, "assets", "manapad-satellite.jpg"), "image/jpeg")),
        json.dumps(uri(os.path.join(ROOT, "assets", "water-mask.png"), "image/png"))))
print("trees", len(trees), "buildings", len(bld))
